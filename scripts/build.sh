#!/bin/zsh
set -eu
cd "${0:A:h}/.."
export CLANG_MODULE_CACHE_PATH="$PWD/.build/clang-cache"
export SWIFTPM_MODULECACHE_OVERRIDE="$PWD/.build/swift-cache"
build_args=(-c release --disable-sandbox -debug-info-format none)
case "${1:-}" in
    --universal) build_args+=(--arch arm64 --arch x86_64) ;;
    "") ;;
    *) print -u2 'Usage: ./scripts/build.sh [--universal]'; exit 1 ;;
esac
swift build "${build_args[@]}"
BIN_DIR="$(swift build "${build_args[@]}" --show-bin-path)"
APP="$PWD/.build/Nest.app"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN_DIR/Nest" "$APP/Contents/MacOS/Nest"
cp Resources/Info.plist "$APP/Contents/Info.plist"
if [ -f Resources/Nest.icns ]; then cp Resources/Nest.icns "$APP/Contents/Resources/"; fi
# ditto replaces matching files without nesting another bundle on repeat builds.
ditto "$BIN_DIR/Nest_Nest.bundle" "$APP/Contents/Resources/Nest_Nest.bundle"
HELPER="$APP/Contents/MacOS/NestBackground"
mkdir -p "$APP/Contents/Library/LaunchAgents"
cp "$BIN_DIR/NestBackground" "$HELPER"
cp Resources/Background/com.nest.local.background.plist "$APP/Contents/Library/LaunchAgents/"
# Remove only the obsolete helper generated by earlier versions of this script.
rm -rf "$APP/Contents/Library/LoginItems/NestBackground.app"
touch "$APP"
printf 'Built %s\n' "$APP"
